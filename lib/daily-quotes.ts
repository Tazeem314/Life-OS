/**
 * Returns a stable daily quote derived deterministically from the date string (YYYY-MM-DD).
 * This ensures that on any given day, the user receives that day's quote consistently,
 * and it automatically transitions to a fresh epic quote every morning.
 */
export function getDailyQuoteForDate(dateKey: string): DailyQuote {
  if (!dateKey) return LEGENDARY_QUOTES[0];

  // Hash the dateKey string to pick an index
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash << 5) - hash + dateKey.charCodeAt(i);
    hash |= 0; // Convert to 32bit integer
  }
  const index = Math.abs(hash) % LEGENDARY_QUOTES.length;
  return LEGENDARY_QUOTES[index];
}

/**
 * Get a random quote different from the current one for manual shuffling
 */
export function getRandomQuoteExcept(currentId: string): DailyQuote {
  const filtered = LEGENDARY_QUOTES.filter((q) => q.id !== currentId);
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || LEGENDARY_QUOTES[0];
}
